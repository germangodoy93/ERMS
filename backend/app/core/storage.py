"""File storage behind a small interface so the provider can change without touching the
modules (ADR-012, ADR-023).

- `S3Storage`: durable. Any S3-compatible service; in production a private Railway bucket.
- `LocalStorage`: server disk, demo mode. On Railway the container disk is ephemeral and
  files are lost on each deploy, so the UI labels photos as a demo.
"""

import re
from functools import lru_cache
from pathlib import Path
from typing import Any, Protocol

import boto3
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError

from app.core.config import Settings, get_settings

_SAFE_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9/_.-]{0,250}$")
_MISSING = frozenset({"NoSuchKey", "404", "NotFound"})


class StorageError(Exception):
    pass


class Storage(Protocol):
    #: True while files are not kept in durable storage.
    demo: bool

    def put(self, key: str, data: bytes) -> None: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...


def _check_key(key: str) -> str:
    # Keys are generated by the application, but never trust them blindly.
    if not _SAFE_KEY.match(key) or ".." in key:
        raise StorageError("Invalid storage key")
    return key


class LocalStorage:
    demo = True

    def __init__(self, root: str | Path) -> None:
        self._root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self._root / _check_key(key)).resolve()
        if not path.is_relative_to(self._root):
            raise StorageError("Invalid storage key")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise StorageError("File not found") from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3Storage:
    """Private bucket: files are only served through the API, which checks permissions."""

    demo = False

    def __init__(self, settings: Settings, client: Any | None = None) -> None:
        if not settings.uses_s3 or settings.s3_secret_access_key is None:
            raise StorageError("S3 storage is not configured")
        self._bucket = settings.s3_bucket
        self._client = client or boto3.client(
            "s3",
            endpoint_url=settings.s3_endpoint,
            region_name=settings.s3_region,
            aws_access_key_id=settings.s3_access_key_id,
            aws_secret_access_key=settings.s3_secret_access_key.get_secret_value(),
            config=Config(
                s3={"addressing_style": settings.s3_addressing_style},
                # boto3 >= 1.36 adds CRC checksums by default; several S3-compatible
                # services reject them, so only send them when the operation requires it.
                request_checksum_calculation="when_required",
                response_checksum_validation="when_required",
                connect_timeout=5,
                read_timeout=20,
                retries={"max_attempts": 3, "mode": "standard"},
            ),
        )

    def put(self, key: str, data: bytes) -> None:
        try:
            self._client.put_object(
                Bucket=self._bucket, Key=_check_key(key), Body=data, ContentType="image/jpeg"
            )
        except (BotoCoreError, ClientError) as exc:
            raise StorageError("Could not store the file") from exc

    def get(self, key: str) -> bytes:
        try:
            response = self._client.get_object(Bucket=self._bucket, Key=_check_key(key))
            body: bytes = response["Body"].read()
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") in _MISSING:
                raise StorageError("File not found") from exc
            raise StorageError("Could not read the file") from exc
        except BotoCoreError as exc:
            raise StorageError("Could not read the file") from exc
        return body

    def delete(self, key: str) -> None:
        try:
            self._client.delete_object(Bucket=self._bucket, Key=_check_key(key))
        except (BotoCoreError, ClientError) as exc:
            raise StorageError("Could not delete the file") from exc

    def ping(self) -> None:
        """Raises StorageError if the bucket cannot be reached with these credentials.

        The message carries only the S3 error code or the exception class (never values),
        so it can be shown in the health check to diagnose the configuration.
        """
        try:
            self._client.head_bucket(Bucket=self._bucket)
        except ClientError as exc:
            error = exc.response.get("Error", {})
            status = exc.response.get("ResponseMetadata", {}).get("HTTPStatusCode")
            raise StorageError(f"S3 {error.get('Code') or '?'} (HTTP {status})") from exc
        except BotoCoreError as exc:
            raise StorageError(type(exc).__name__) from exc


@lru_cache
def get_storage() -> Storage:
    settings = get_settings()
    if settings.uses_s3:
        return S3Storage(settings)
    return LocalStorage(settings.attachments_dir)
